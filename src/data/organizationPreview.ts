    atasan: values.atasan,
    tipe_kontrak: values.tipe_kontrak || "PKWTT",
    lokasi_kerja: values.lokasi_kerja || values.cabang,
    shift: values.shift || "Regular",
    jenis_kelamin: values.jenis_kelamin || null,
    agama: values.agama || null,
    tempat_lahir: values.tempat_lahir || null,
    status_pernikahan: values.status_pernikahan || null,
    tanggal_lahir: values.tanggal_lahir || null,
    kewarganegaraan: values.kewarganegaraan || "Indonesia",
