    no_ktp: values.no_ktp || null,
    no_kk: values.no_kk || null,
    npwp: values.npwp || null,
    bpjs_kesehatan: values.bpjs_kesehatan || null,
    bpjs_ketenagakerjaan: values.bpjs_ketenagakerjaan || null,
    passport: values.passport || null,
    no_hp: values.no_hp || null,
    email_pribadi: values.email_pribadi || null,
    email_kantor: values.email_kantor || null,
    alamat_ktp: values.alamat_ktp || null,
    alamat_domisili: values.alamat_domisili || null,
    kota: values.kota || null,
    provinsi: values.provinsi || null,
    kode_pos: values.kode_pos || null,
    kontak_darurat: values.kontak_darurat || null,
    pendidikan: values.pendidikan || [],
